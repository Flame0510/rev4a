#!/usr/bin/env bash
# olympus.sh — clone, configure, and start the Olympus dashboard
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/helpers.sh"

OLYMPUS_REPO="${OLYMPUS_REPO:-https://github.com/Flame0510/olympus.git}"
OLYMPUS_BRANCH="${OLYMPUS_BRANCH:-main}"
OLYMPUS_PORT="${OLYMPUS_PORT:-3740}"

# ------------------------------------------------------------------------------
# Install Node.js (>= 18) if not present
install_node() {
  if has_cmd node; then
    local node_ver
    node_ver=$(node -v | sed 's/v//' | cut -d. -f1)
    if [[ $node_ver -ge 18 ]]; then
      log_ok "Node.js $(node -v) is already installed"
      return 0
    fi
  fi

  log_info "Installing Node.js 22 LTS via NodeSource..."
  curl -fsSL https://deb.nodesource.com/setup_22.x | $SUDO bash -
  $SUDO apt-get install -y nodejs

  if ! has_cmd node; then
    die "Node.js installation failed."
  fi
  log_ok "Node.js $(node -v) installed"
}

# ------------------------------------------------------------------------------
# Install system dependencies (git, curl, openssl, etc.)
install_system_deps() {
  log_info "Installing system dependencies..."
  $SUDO apt-get update -qq
  $SUDO apt-get install -y -qq git curl openssl jq build-essential python3

  for dep in git curl openssl; do
    if has_cmd "$dep"; then
      log_ok "$dep is available"
    else
      log_warn "$dep is not available — some features may not work"
    fi
  done
  log_ok "Build tools installed (gcc, make, python3 — required for native modules)"
}

# ------------------------------------------------------------------------------
# Clone or update the Olympus repository
clone_olympus() {
  ensure_dir "$OLYMPUS_ROOT"

  if [[ -d "${OLYMPUS_APP}/.git" ]]; then
    log_info "Olympus repository already exists. Pulling latest..."
    cd "$OLYMPUS_APP"
    $SUDO git fetch origin
    $SUDO git checkout "$OLYMPUS_BRANCH"
    $SUDO git pull origin "$OLYMPUS_BRANCH"
    log_ok "Olympus repository updated"
  else
    log_info "Cloning Olympus repository..."
    $SUDO git clone --branch "$OLYMPUS_BRANCH" "$OLYMPUS_REPO" "$OLYMPUS_APP"
    log_ok "Olympus repository cloned to $OLYMPUS_APP"
  fi
}

# ------------------------------------------------------------------------------
# Run npm install
npm_install() {
  cd "$OLYMPUS_APP"

  if [[ -d node_modules ]]; then
    log_info "node_modules exists. Running npm ci..."
    $SUDO npm ci
    log_ok "npm ci complete"
  else
    log_info "Installing dependencies (npm install)..."
    $SUDO npm install
    log_ok "npm install complete"
  fi
}

# ------------------------------------------------------------------------------
# Create .env file if it doesn't exist
create_env() {
  local env_file="${OLYMPUS_APP}/.env"

  if [[ -f "$env_file" ]]; then
    log_ok ".env file already exists — keeping existing configuration"
    return 0
  fi

  log_info "Creating .env file..."
  log_warn "No .env found. Generating new credentials."

  local password jwt_secret token
  password=$(random_string 24)
  jwt_secret=$(random_string 48)
  token=$(random_string 32)

  cat > "$env_file" << ENVEOF
# Olympus environment — generated by setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Keep this file secret. It is gitignored by default.

# Dashboard login password
OLYMPUS_PASSWORD=${password}

# API token (used for programmatic access and Control UI bootstrap)
OLYMPUS_TOKEN=${token}

# JWT signing secret (used for session cookies)
OLYMPUS_JWT_SECRET=${jwt_secret}

# Path to the events database (optional, default: data/events.db)
# OLYMPUS_DB=data/events.db

# Workspace root for local file explorer (optional)
# OLYMPUS_WORKSPACE_ROOT=/home

# Provider API keys (add them via the Providers UI or below)
# PROVIDER_OPENAI_KEY=
# PROVIDER_DEEPSEEK_KEY=
# PROVIDER_OPENROUTER_KEY=
# PROVIDER_GROQ_KEY=
# PROVIDER_CODEX_KEY=
ENVEOF

  $SUDO chmod 600 "$env_file"
  log_ok ".env created with random passwords"
  log_warn "Credentials saved to ${env_file}:"
  log_info "  Password: ${password}"
  log_info "  Token:    ${token}"
  log_info "  Save these credentials somewhere safe. You will need them to log in."
}

# ------------------------------------------------------------------------------
# Create data directories
create_data_dirs() {
  ensure_dir "$OLYMPUS_DATA"
  ensure_dir "${OLYMPUS_APP}/data"

  # Initialize provider-keys.json if missing
  if [[ ! -f "${OLYMPUS_APP}/data/provider-keys.json" ]]; then
    echo '{}' | $SUDO tee "${OLYMPUS_APP}/data/provider-keys.json" > /dev/null
    log_info "Initialized data/provider-keys.json"
  fi

  # Initialize agents-token.json if missing
  if [[ ! -f "${OLYMPUS_APP}/data/agents-token.json" ]]; then
    local agents_token
    agents_token=$(random_string 24)
    cat > /tmp/agents-token.json << JSONEOF
{
  "token": "${agents_token}",
  "created": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "description": "Shared gateway token for agent Control UI bootstrap"
}
JSONEOF
    $SUDO mv /tmp/agents-token.json "${OLYMPUS_APP}/data/agents-token.json"
    $SUDO chmod 600 "${OLYMPUS_APP}/data/agents-token.json"
    log_info "Generated agents gateway token"
  fi
}

# ------------------------------------------------------------------------------
# Create shared volumes (skills, repos, memory)
create_shared_volumes() {
  local shared_skills="/docker/shared-skills"
  local shared_repos="/docker/shared-repos"

  for dir in "$shared_skills" "$shared_repos"; do
    if [[ ! -d "$dir" ]]; then
      log_info "Creating shared volume: $dir"
      $SUDO mkdir -p "$dir"
      # uid 1000 = node (default user in agent containers)
      if id -u 1000 &>/dev/null; then
        $SUDO chown 1000:1000 "$dir"
      else
        log_warn "uid 1000 not found on host — shared volume ownership may be wrong"
      fi
      $SUDO chmod 2775 "$dir"
      log_ok "Shared volume created: $dir"
    else
      log_ok "Shared volume already exists: $dir"
    fi
  done
}

# ------------------------------------------------------------------------------
# Build the Next.js app
build_olympus() {
  cd "$OLYMPUS_APP"
  log_info "Building Olympus (this may take a minute)..."
  $SUDO npm run build
  log_ok "Build complete"
}

# ------------------------------------------------------------------------------
# Read .env and build Environment= lines for systemd units
_build_env_lines() {
  local env_lines=""
  if [[ -f "${OLYMPUS_APP}/.env" ]]; then
    while IFS='=' read -r line; do
      [[ "$line" =~ ^# ]] && continue
      [[ -z "$line" ]] && continue
      [[ "$line" != *"="* ]] && continue
      local key="${line%%=*}"
      local value="${line#*=}"
      # Forward OLYMPUS_, PROVIDER_, and OPENCLAW_ env vars plus PATH-aware vars
      [[ "$key" =~ ^(OLYMPUS_|PROVIDER_|OPENCLAW_|NODE_) ]] || continue
      env_lines+="Environment=${key}=${value}"$'\n'
    done < "${OLYMPUS_APP}/.env"
  fi
  echo "$env_lines"
}

# ------------------------------------------------------------------------------
# Resolve node binary path (nvm-aware)
_resolve_node_path() {
  if command -v node &>/dev/null; then
    command -v node
  elif [[ -f "${HOME}/.nvm/nvm.sh" ]]; then
    source "${HOME}/.nvm/nvm.sh" 2>/dev/null
    command -v node || echo "/usr/bin/node"
  else
    echo "/usr/bin/node"
  fi
}

# ------------------------------------------------------------------------------
# Create systemd service units (next + daemon + terminal-ws)
create_systemd_service() {
  local next_service="/etc/systemd/system/olympus-next.service"
  local daemon_service="/etc/systemd/system/olympus-daemon.service"
  local ws_service="/etc/systemd/system/olympus-terminal-ws.service"

  if systemctl is-enabled olympus-next &>/dev/null; then
    log_ok "Systemd services already exist"
    return 0
  fi

  log_info "Creating systemd services..."

  local node_path
  node_path=$(_resolve_node_path)

  local env_lines
  env_lines=$(_build_env_lines)

  # Determine node bin directory (for PATH in service units)
  local node_bin_dir
  node_bin_dir=$(dirname "$node_path")

  local shared_env
  shared_env="Environment=NODE_ENV=production
Environment=PATH=${node_bin_dir}:/usr/local/bin:/usr/bin:/bin
Environment=OLYMPUS_DB=${OLYMPUS_APP}/data/events.db
${env_lines}"

  # Resolve next binary (in node_modules/.bin, not alongside node)
  local next_path="${OLYMPUS_APP}/node_modules/.bin/next"
  if [[ ! -x "$next_path" ]]; then
    # Fallback: use npx (may be slower but always works)
    next_path="npx next"
  fi

  # ── olympus-next.service ────────────────────────────────────────────
  if [[ "$next_path" == "npx next" ]]; then
    $SUDO tee "$next_service" > /dev/null << SERVICEEOF
[Unit]
Description=Olympus Dashboard (Next.js)
After=network.target docker.service
Wants=docker.service
PartOf=olympus.target

[Service]
Type=simple
User=${USER}
WorkingDirectory=${OLYMPUS_APP}
Environment=PORT=${OLYMPUS_PORT}
${shared_env}ExecStart=${node_bin_dir}/npx next start -p ${OLYMPUS_PORT}
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=olympus.target
SERVICEEOF
  else
    $SUDO tee "$next_service" > /dev/null << SERVICEEOF
[Unit]
Description=Olympus Dashboard (Next.js)
After=network.target docker.service
Wants=docker.service
PartOf=olympus.target

[Service]
Type=simple
User=${USER}
WorkingDirectory=${OLYMPUS_APP}
Environment=PORT=${OLYMPUS_PORT}
${shared_env}ExecStart=${next_path} start -p ${OLYMPUS_PORT}
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=olympus.target
SERVICEEOF
  fi

  # ── olympus-daemon.service ──────────────────────────────────────────
  $SUDO tee "$daemon_service" > /dev/null << SERVICEEOF
[Unit]
Description=Olympus Daemon (session poller + metrics)
After=olympus-next.service
Wants=olympus-next.service
PartOf=olympus.target

[Service]
Type=simple
User=${USER}
WorkingDirectory=${OLYMPUS_APP}
${shared_env}ExecStart=${node_path} daemon.js
Restart=always
RestartSec=10
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=olympus.target
SERVICEEOF

  # ── olympus-terminal-ws.service ─────────────────────────────────────
  $SUDO tee "$ws_service" > /dev/null << SERVICEEOF
[Unit]
Description=Olympus Terminal WebSocket
After=olympus-next.service
Wants=olympus-next.service
PartOf=olympus.target

[Service]
Type=simple
User=${USER}
WorkingDirectory=${OLYMPUS_APP}
Environment=TERMINAL_WS_PORT=3741
${shared_env}ExecStart=${node_path} terminal-ws-server.js
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=olympus.target
SERVICEEOF

  # ── olympus.target ──────────────────────────────────────────────────
  $SUDO tee /etc/systemd/system/olympus.target > /dev/null << TARGETEOF
[Unit]
Description=Olympus Dashboard (all services)
Wants=olympus-next.service olympus-daemon.service olympus-terminal-ws.service
After=network.target docker.service

[Install]
WantedBy=multi-user.target
TARGETEOF

  $SUDO systemctl daemon-reload
  log_ok "Systemd services created:"
  log_info "  - olympus-next.service       (Next.js dashboard)"
  log_info "  - olympus-daemon.service       (session poller)"
  log_info "  - olympus-terminal-ws.service  (WebSocket PTY)"
  log_info "  - olympus.target              (boots all three)"
}

# ------------------------------------------------------------------------------
# Build the agent base image (used to create agent containers)
build_agent_image() {
  local dockerfile_dir="${OLYMPUS_APP}/agent-templates/base-image"

  if [[ ! -f "${dockerfile_dir}/Dockerfile" ]]; then
    log_warn "Agent base image Dockerfile not found at ${dockerfile_dir} — skipping"
    return 0
  fi

  if docker image inspect openclaw-agent-base:latest &>/dev/null; then
    log_ok "Agent base image (openclaw-agent-base:latest) already exists"
    return 0
  fi

  log_info "Building agent base image (this will take a few minutes)..."
  log_info "  → pulling node:24-bookworm-slim + installing OpenClaw + tooling"
  cd "${dockerfile_dir}"
  docker build -t openclaw-agent-base:latest .
  log_ok "Agent base image built successfully"
}

# ------------------------------------------------------------------------------
# Start all Olympus services via systemd target
start_olympus() {
  log_info "Starting Olympus services..."

  # Enable at boot (olympus.target pulls all three services via Wants)
  $SUDO systemctl enable olympus.target 2>/dev/null || true

  if systemctl is-active --quiet olympus.target; then
    log_info "Restarting Olympus services..."
    $SUDO systemctl restart olympus.target
  else
    log_info "Starting Olympus target..."
    $SUDO systemctl start olympus.target
  fi

  # Wait for Next.js to come up
  log_info "Waiting for Olympus to start (up to 30s)..."
  for i in $(seq 1 15); do
    if curl -sf --max-time 2 "http://127.0.0.1:${OLYMPUS_PORT}/api/health" &>/dev/null; then
      log_ok "Olympus Next.js is running and healthy"
      break
    fi
    sleep 2
  done

  # Verify all three services
  local all_ok=true
  for svc in olympus-next olympus-daemon olympus-terminal-ws; do
    if systemctl is-active --quiet "$svc"; then
      log_ok "$svc is active"
    else
      log_error "$svc failed to start"
      log_error "Check logs: sudo journalctl -u $svc --no-pager -n 20"
      all_ok=false
    fi
  done

  if ! $all_ok; then
    log_error "Some services did not start. Review logs above."
    return 1
  fi

  return 0
}

# ------------------------------------------------------------------------------
print_summary() {
  local host_ip
  host_ip=$(hostname -I | awk '{print $1}')

  # Try public IP (works on cloud VPS)
  local public_ip
  public_ip=$(curl -sf --max-time 5 ifconfig.me 2>/dev/null || echo "")
  if [[ -n "$public_ip" ]]; then
    host_ip="$public_ip"
  fi

  # Read credentials from .env (if they exist)
  local olympus_password="(see .env)"
  local olympus_token="(see .env)"
  if [[ -f "${OLYMPUS_APP}/.env" ]]; then
    olympus_password=$(grep -E '^OLYMPUS_PASSWORD=' "${OLYMPUS_APP}/.env" | cut -d= -f2- || echo "(not set)")
    olympus_token=$(grep -E '^OLYMPUS_TOKEN=' "${OLYMPUS_APP}/.env" | cut -d= -f2- || echo "(not set)")
  fi

  echo ""
  echo "=============================================="
  echo "  Olympus is ready!"
  echo "=============================================="
  echo ""
  echo "  URL:          http://${host_ip}:${OLYMPUS_PORT}"
  echo ""
  echo "  ── Credentials (save these!) ──"
  echo "  Password:     ${olympus_password}"
  echo "  API Token:    ${olympus_token}"
  echo ""
  echo "  ── Service management ──"
  echo "  Status:       sudo systemctl status olympus.target"
  echo "  Restart:      sudo systemctl restart olympus.target"
  echo "  Stop:         sudo systemctl stop olympus.target"
  echo "  Next.js logs: sudo journalctl -u olympus-next -f"
  echo "  Daemon logs:  sudo journalctl -u olympus-daemon -f"
  echo "  Config:       ${OLYMPUS_APP}/.env"
  echo ""
  echo "  ── Firewall (if using UFW) ──"
  echo "  sudo ufw allow ${OLYMPUS_PORT}/tcp"
  echo ""
  echo "  ── First-time setup ──"
  echo "  1. Open http://${host_ip}:${OLYMPUS_PORT} in your browser"
  echo "  2. You'll be redirected to the setup wizard"
  echo "  3. Set your admin password and build the agent image"
  echo "  4. After login, the wizard guides you through:"
  echo "     • Adding provider API keys"
  echo "     • Creating your first agent"
  echo ""
  echo "  Olympus auto-starts on every system reboot."
  echo "  Run this script again anytime — it's safe."
  echo "=============================================="
}

# ------------------------------------------------------------------------------
setup_olympus() {
  log_info "--- Olympus setup ---"
  install_system_deps
  install_node
  clone_olympus
  npm_install
  create_data_dirs
  create_shared_volumes
  create_env
  build_olympus
  build_agent_image
  create_systemd_service
  start_olympus
  print_summary
  log_ok "Olympus setup complete"
}
