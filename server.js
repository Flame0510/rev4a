#!/usr/bin/env node
/**
 * Rev4a web server — Next.js plus the container terminal on the same port.
 *
 * `rev4a serve` runs this instead of `next start`. Every HTTP request goes to Next.js
 * unchanged. The one addition is the WebSocket upgrade on `/api/terminal-ws`: the browser
 * opens the terminal on the dashboard's own host and port, and this server forwards it to
 * the terminal server (terminal-ws-server.js, 127.0.0.1 only) — so the terminal works with
 * no reverse proxy in front, locally and on a plain-IP VPS. Before forwarding it checks:
 *
 *   1. the session cookie (`rev4a_token`, the same JWT the dashboard pages require);
 *   2. the Origin header matches the host the browser addressed — `Host`, or
 *      `X-Forwarded-Host` behind a proxy that rewrites Host — so a page on another site
 *      cannot open a shell with the user's cookie (cross-site WebSocket hijacking; a
 *      browser cannot set X-Forwarded-Host on a WebSocket, so trusting it opens nothing);
 *   3. the container name is well formed (the terminal server checks it exists and runs).
 *
 * The forwarded request carries a per-boot secret (REV4A_TERMINAL_SECRET, generated by
 * `rev4a serve` for both processes) and no cookie; the terminal server refuses anything
 * without that secret, so reaching 127.0.0.1:3741 directly gives nothing.
 */
'use strict';

const http = require('http');
const net = require('net');
const fs = require('fs');
const os = require('os');
const path = require('path');
const next = require('next');
const { CLIENT_IP_HEADER, clientAddress, parseTrustedProxies } = require('./lib/client-address.js');

const PORT = parseInt(process.env.PORT || '3740', 10);
const TERMINAL_WS_PORT = parseInt(process.env.TERMINAL_WS_PORT || '3741', 10);
const TERMINAL_SECRET = process.env.REV4A_TERMINAL_SECRET || '';
const TERMINAL_PATH = '/api/terminal-ws';
// The version this process runs and when it started, fixed once here. npm replaces
// package.json on disk before the build and the restart, so the file cannot say which
// version is answering; /api/update-status and the update state read these instead.
try {
  process.env.REV4A_RUNNING_VERSION = JSON.parse(fs.readFileSync(path.join(__dirname, 'package.json'), 'utf8')).version || '';
} catch {
  process.env.REV4A_RUNNING_VERSION = '';
}
process.env.REV4A_STARTED_AT = String(Date.now());
// Only this process resolves a `restarting` update (lib/update-state.js). Children inherit
// the variable but have another pid, so they never mark an update done.
process.env.REV4A_SERVER_PID = String(process.pid);

/** Docker container names and ids: what `docker exec` accepts, nothing a shell could read. */
const CONTAINER_RE = /^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}$/;

// Same data directory rule as lib/rev4a-paths.ts, for the JWT secret fallback below.
const DATA_DIR = process.env.REV4A_DATA_DIR
  || (process.platform === 'win32'
    ? path.join(process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming'), 'rev4a')
    : path.join(os.homedir(), '.config', 'rev4a'));

/** REV4A_JWT_SECRET from the environment, else from .env — the rule lib/rev4a-auth.js follows. */
function jwtSecret() {
  if (process.env.REV4A_JWT_SECRET) return process.env.REV4A_JWT_SECRET;
  try {
    const m = /^REV4A_JWT_SECRET=(.*)$/m.exec(fs.readFileSync(path.join(DATA_DIR, '.env'), 'utf8'));
    return m ? m[1].trim() : '';
  } catch {
    return '';
  }
}

function cookieValue(header, name) {
  for (const part of String(header || '').split(';')) {
    const i = part.indexOf('=');
    if (i > 0 && part.slice(0, i).trim() === name) {
      try {
        return decodeURIComponent(part.slice(i + 1).trim());
      } catch {
        return ''; // malformed escape: treated as no cookie (401)
      }
    }
  }
  return '';
}

/** Answer an upgrade with a plain HTTP status and close — the browser sees a failed connection. */
function refuse(socket, status, reason) {
  if (socket.writable) {
    socket.write(`HTTP/1.1 ${status} ${reason}\r\nConnection: close\r\nContent-Length: 0\r\n\r\n`);
  }
  socket.destroy();
}

let jwtVerify = null;

async function authorised(req) {
  const token = cookieValue(req.headers.cookie, 'rev4a_token');
  const secret = jwtSecret();
  if (!token || !secret) return false;
  try {
    jwtVerify = jwtVerify || (await import('jose')).jwtVerify;
    await jwtVerify(token, new TextEncoder().encode(secret));
    return true;
  } catch {
    return false;
  }
}

/** host[:port] lower-cased, without the scheme's default port (`x:80` on http is `x`). */
function normaliseHost(host, protocol) {
  const h = String(host || '').trim().toLowerCase();
  const port = protocol === 'https:' ? ':443' : ':80';
  return h.endsWith(port) ? h.slice(0, -port.length) : h;
}

function sameOrigin(req) {
  const origin = req.headers.origin;
  if (!origin) return false; // browsers always send it on a WebSocket handshake
  let url;
  try {
    url = new URL(origin);
  } catch {
    return false;
  }
  const want = normaliseHost(url.host, url.protocol);
  const forwarded = String(req.headers['x-forwarded-host'] || '').split(',')[0];
  return [req.headers.host, forwarded].some((h) => h && normaliseHost(h, url.protocol) === want);
}

/** Replay the handshake to the terminal server — without the cookie, with the secret — then splice the sockets. */
function forwardToTerminal(req, socket, head) {
  const upstream = net.connect(TERMINAL_WS_PORT, '127.0.0.1');
  let connected = false;
  // Until the terminal server answers the handshake: a hung server must not hold the browser forever.
  upstream.setTimeout(10000, () => (connected ? close() : refuse(socket, 504, 'Gateway Timeout')));
  upstream.once('data', () => upstream.setTimeout(0));
  upstream.on('connect', () => {
    connected = true;
    const lines = [`${req.method} ${req.url} HTTP/1.1`];
    for (let i = 0; i < req.rawHeaders.length; i += 2) {
      const name = req.rawHeaders[i];
      const lower = name.toLowerCase();
      if (lower === 'cookie' || lower === 'x-rev4a-terminal-secret') continue;
      lines.push(`${name}: ${req.rawHeaders[i + 1]}`);
    }
    lines.push(`X-Rev4a-Terminal-Secret: ${TERMINAL_SECRET}`);
    upstream.write(lines.join('\r\n') + '\r\n\r\n');
    if (head && head.length) upstream.write(head);
    socket.pipe(upstream).pipe(socket);
  });
  const close = () => { socket.destroy(); upstream.destroy(); };
  // Before the splice an error is answered as HTTP; after it, the stream is WebSocket frames.
  upstream.on('error', () => (connected ? close() : refuse(socket, 502, 'Bad Gateway')));
  upstream.on('close', close);
  socket.on('error', close);
  socket.on('close', close);
}

async function onUpgrade(req, socket, head) {
  socket.on('error', () => socket.destroy());
  let url;
  try {
    url = new URL(req.url || '/', 'http://localhost');
  } catch {
    return refuse(socket, 400, 'Bad Request');
  }
  // Production Next.js takes no other upgrade (hot reload is a `next dev` feature).
  if (url.pathname !== TERMINAL_PATH) return refuse(socket, 404, 'Not Found');
  if (!sameOrigin(req)) return refuse(socket, 403, 'Forbidden');
  if (!(await authorised(req))) return refuse(socket, 401, 'Unauthorized');
  if (!CONTAINER_RE.test(url.searchParams.get('id') || '')) return refuse(socket, 400, 'Bad Request');
  if (!TERMINAL_SECRET) return refuse(socket, 503, 'Service Unavailable');
  forwardToTerminal(req, socket, head);
}

async function main() {
  // Proxies (none by default, loopback included) whose X-Forwarded-For names the client for the login throttle.
  // Parsed once; invalid entries are ignored with a single warning.
  const trustedProxies = parseTrustedProxies(process.env.REV4A_TRUSTED_PROXIES);
  if (trustedProxies.invalid.length) {
    console.warn(`[rev4a] REV4A_TRUSTED_PROXIES: ignored invalid entries: ${trustedProxies.invalid.join(', ')}`);
  }
  if (trustedProxies.wide.length) {
    console.warn(`[rev4a] REV4A_TRUSTED_PROXIES trusts a very wide range (${trustedProxies.wide.join(', ')}): any client in it can choose its own login throttle key`);
  }
  const app = next({ dev: false, dir: __dirname, port: PORT });
  await app.prepare();
  const handle = app.getRequestHandler();
  const server = http.createServer((req, res) => {
    // The login throttle keys on this header: a client must never be able to set it itself.
    delete req.headers[CLIENT_IP_HEADER];
    req.headers[CLIENT_IP_HEADER] = clientAddress(req.socket.remoteAddress, req.headers['x-forwarded-for'], trustedProxies);
    handle(req, res);
  });
  server.on('upgrade', (req, socket, head) => {
    onUpgrade(req, socket, head).catch(() => socket.destroy());
  });
  server.listen(PORT, () => {
    console.log(`[rev4a] Ready on port ${PORT} (terminal on ${TERMINAL_PATH} → 127.0.0.1:${TERMINAL_WS_PORT})`);
    if (!TERMINAL_SECRET) console.log('[rev4a] REV4A_TERMINAL_SECRET is not set: the terminal is disabled (start with `rev4a serve`).');
  });
  // Open terminal sockets keep close() waiting; give them a moment, then go.
  const stop = () => {
    server.close(() => process.exit(0));
    setTimeout(() => process.exit(0), 3000).unref();
  };
  process.on('SIGTERM', stop);
  process.on('SIGINT', stop);
}

main().catch((err) => {
  console.error('[rev4a] Failed to start:', err);
  process.exit(1);
});
